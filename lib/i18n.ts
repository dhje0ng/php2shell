export function translate(text: string, language: Language): string {
  if (language === 'ko') return text;
  const key = text.trim();
  if (!key || !Object.hasOwn(english, key)) return text;
  return text.replace(key, english[key]);
}

export function normalizeLanguage(value: string | null): Language {
  return value === 'en' ? 'en' : 'ko';
}

export function patchReference(version: string, language: Language): string {
  return language === 'en' ? `Official patch level: PHP ${version} or later. ` : `공식 패치 기준: PHP ${version} 이상. `;
}
